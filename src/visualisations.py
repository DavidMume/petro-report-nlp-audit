def normalise_cited_source(s: str) -> str:
    s = str(s)
    rules = [(r"contralor", "Contraloría (CGR)"), (r"procurad", "Procuraduría"), (r"fiscal[ií]a", "Fiscalía"),
             (r"consejo de estado", "Consejo de Estado"), (r"corte", "Cortes"), (r"siif", "SIIF Nación"),
             (r"secop", "SECOP"), (r"superintendencia", "Superintendencias"), (r"dian", "DIAN"), (r"dane", "DANE"),
             (r"campetrol", "CAMPETROL"), (r"cambio", "Revista Cambio"), (r"nota al pie", "Nota al pie"),
             (r"entidad|registros|información|datos|reportes?", "Registros/datos de la entidad (genérico)")]
    for pat, lab in rules:
        if re.search(pat, s, re.I):
            return lab
    return "Otra"


