    s = pd.Series(years)
    s = s[(s >= 2010) & (s <= 2036)].value_counts().sort_index()
    fig, ax = plt.subplots(figsize=(9, 3.4))
    ax.bar(s.index, s.values, width=0.7, color=SERIES_1)
    ax.axvspan(2022.6, 2026.6, color="#f0efec", zorder=0)
    ax.text(2024.6, s.max() * 1.04, "Periodo 2022–2026", ha="center", fontsize=8, color=INK_2)
