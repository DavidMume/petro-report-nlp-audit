def setup_style() -> None:
    plt.rcParams.update({
        "figure.facecolor": SURFACE, "axes.facecolor": SURFACE, "savefig.facecolor": SURFACE,
        "font.family": "DejaVu Sans", "font.size": 9.5, "text.color": INK, "axes.labelcolor": INK_2,
        "axes.edgecolor": AXIS, "axes.linewidth": 0.8, "xtick.color": MUTED, "ytick.color": INK_2,
        "xtick.labelsize": 8.5, "ytick.labelsize": 8.5, "axes.grid": False, "grid.color": GRID,
        "grid.linewidth": 0.8, "grid.linestyle": "-", "axes.spines.top": False, "axes.spines.right": False,
        "axes.titlesize": 12, "axes.titleweight": "bold", "axes.titlelocation": "left", "axes.titlepad": 12,
        "legend.frameon": False, "legend.fontsize": 8.5,
    })


def _finish(fig, ax_or_none, out_path: Path, subtitle: str = "", note: str = SOURCE_NOTE) -> None:
    # Notes sit below the figure area; bbox_inches="tight" expands the canvas to include them,
    # so they never collide with axis labels.
    y = -0.02
    if subtitle:
        fig.text(0.01, y, subtitle, fontsize=7.5, color=INK_2, ha="left", va="top", wrap=True)
        y -= 0.045
    fig.text(0.01, y, note, fontsize=7, color=MUTED, ha="left", va="top")
    out_path.parent.mkdir(parents=True, exist_ok=True)
    fig.savefig(out_path, dpi=150, bbox_inches="tight", pad_inches=0.25)
    plt.close(fig)


def _hbar(ax, labels, values, color=SERIES_1, fmt="{:,.0f}", max_label=None):
    y = np.arange(len(labels))[::-1]
    ax.barh(y, values, height=0.62, color=color, edgecolor=SURFACE, linewidth=1)
    ax.set_yticks(y, labels)
    ax.xaxis.grid(True)
    ax.set_axisbelow(True)
    ax.spines["left"].set_visible(False)
    ax.tick_params(axis="y", length=0)
    vmax = max(values) if len(values) else 1
    for yi, v in zip(y, values):
        ax.text(v + vmax * 0.01, yi, fmt.format(v), va="center", fontsize=7.5, color=INK_2)
    ax.set_xlim(0, vmax * 1.12)


def _short(s: str, n: int = 48) -> str:
    return s if len(s) <= n else s[: n - 1] + "…"


