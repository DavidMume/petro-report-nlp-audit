def plot_stylometry_heatmap(features: pd.DataFrame, segments: pd.DataFrame, out: Path, cols: list[str]) -> None:
    X = features.set_index("segment_id")[cols]
    Z = (X - X.mean()) / X.std()
    fig, ax = plt.subplots(figsize=(13, 5))
    div = LinearSegmentedColormap.from_list("div", ["#184f95", "#6da7ec", "#f0efec", "#e66767", "#b3302f"])
    im = ax.imshow(Z.T.values, cmap=div, aspect="auto", vmin=-3, vmax=3)
    ax.set_yticks(range(len(cols)), cols, fontsize=7.5)
    seg = segments.set_index("segment_id")
    ticks = list(range(0, len(Z), 3))
    ax.set_xticks(ticks, [f"{Z.index[i]}\np{seg.loc[Z.index[i], 'page_start']}" for i in ticks], fontsize=6.5)
    ch = seg.loc[Z.index, "chapter"].values
    for i in range(1, len(ch)):
        if ch[i] != ch[i - 1]:
            ax.axvline(i - 0.5, color=INK, lw=0.8)
    cb = fig.colorbar(im, ax=ax, fraction=0.015, pad=0.01)
    cb.set_label("z-score", color=INK_2); cb.outline.set_visible(False)
    ax.set_title("Mapa estilométrico por segmento (~700 palabras); líneas = límites de capítulo")
    _finish(fig, ax, out, "Rasgos estandarizados. Un contraste de color indica diferencia estilística, no autoría ni uso de IA.")


