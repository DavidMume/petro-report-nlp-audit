def plot_network(graph_json: dict, out: Path, title: str, top_n: int = 40, label_n: int = 10,
                 color_by: str | None = "entity_type") -> None:
    import networkx as nx

    G = nx.Graph()
    for n in graph_json["nodes"]:
        G.add_node(n["id"], **n)
    for l in graph_json["links"]:
        G.add_edge(l["source"], l["target"], weight=l["weight"])
    if G.number_of_nodes():
        G = G.subgraph(max(nx.connected_components(G), key=len)).copy()  # largest connected component
    keep = sorted(G.nodes, key=lambda n: -G.nodes[n].get("weighted_degree", 0))[:top_n]
    H = G.subgraph(keep).copy()
    pos = nx.spring_layout(H, seed=7, k=0.9, weight="weight", iterations=200)
    fig, ax = plt.subplots(figsize=(10, 7.5))
    w = np.array([H[u][v]["weight"] for u, v in H.edges])
    nx.draw_networkx_edges(H, pos, ax=ax, width=0.4 + 1.6 * (w / w.max()) if len(w) else 1, edge_color=AXIS, alpha=0.8)
    if color_by:
        types = [H.nodes[n].get(color_by, "") for n in H.nodes]
        cols = [CATEGORICAL[ENTITY_TYPES_SHOWN.index(t)] if t in ENTITY_TYPES_SHOWN else MUTED for t in types]
    else:
        cols = SERIES_1
    sizes = [30 + 8 * H.nodes[n].get("count", 1) for n in H.nodes]
    nx.draw_networkx_nodes(H, pos, ax=ax, node_size=sizes, node_color=cols, edgecolors=SURFACE, linewidths=1.5)
    top_labels = sorted(H.nodes, key=lambda n: -H.nodes[n].get("weighted_degree", 0))[:label_n]
    for n in top_labels:
        x, y = pos[n]
        ax.text(x + 0.03, y, _short(n, 34), fontsize=7.5, ha="left", va="center", color=INK,
                bbox=dict(boxstyle="round,pad=0.15", fc=SURFACE, ec="none", alpha=0.8))
    if color_by:
        handles = [plt.Line2D([], [], marker="o", ls="", color=CATEGORICAL[i], markersize=7)
                   for i in range(len(ENTITY_TYPES_SHOWN))]
        ax.legend(handles, [ENTITY_TYPE_ES[t] for t in ENTITY_TYPES_SHOWN], loc="lower left")
    ax.set_title(title)
    ax.axis("off")
    _finish(fig, ax, out, f"Componente conexo principal, top {len(H)} nodos por grado ponderado; arista = coaparición en el mismo "
                          "párrafo (entidades) u oración (conceptos). Posiciones 2D ilustrativas; grafo completo en outputs/networks/.")


# --- 9-11 Topics & embeddings --------------------------------------------------------------------

def plot_topic_distribution(summary: pd.DataFrame, out: Path) -> None:
    models = [("tfidf_nmf", "TF-IDF + NMF"), ("lda", "LDA"), ("embedding_kmeans", "Embeddings + k-means")]
    fig, axes = plt.subplots(1, 3, figsize=(13.5, 5.2), sharex=True)
    for ax, (m, name) in zip(axes, models):
        d = summary[summary.model == m].sort_values("share_paragraphs", ascending=False)
        labels = [f"T{t}: " + ", ".join(s.split(", ")[:3]) for t, s in zip(d.topic, d.top_terms)]
        _hbar(ax, labels, (d.share_paragraphs * 100).values, fmt="{:.0f}%")
        ax.set_title(name, fontsize=10)
        ax.set_xlabel("% de párrafos (tema dominante)")
    fig.suptitle("Distribución de temas según tres modelos (sin etiquetas interpretativas)", x=0.01, ha="left",
                 fontweight="bold", fontsize=12)
    fig.tight_layout(rect=(0, 0.03, 1, 0.95))
    _finish(fig, None, out, "Los temas se describen solo con sus 3 términos principales. Acuerdo entre modelos bajo (ver topic_model_agreement.csv).")


def plot_topics_by_section(tbc: pd.DataFrame, summary: pd.DataFrame, out: Path, model: str = "tfidf_nmf") -> None:
    d = tbc[tbc.model == model].pivot(index="chapter", columns="dominant_topic", values="share").fillna(0)
    d = d.reindex([c for c in CHAPTER_ORDER if c in d.index])
    names = summary[summary.model == model].set_index("topic").top_terms.map(lambda s: ", ".join(s.split(", ")[:2]))
    fig, ax = plt.subplots(figsize=(12, 3.8))
    im = ax.imshow(d.values * 100, cmap=BLUE_CMAP, aspect="auto", vmin=0)
    ax.set_yticks(range(len(d.index)), [CHAPTER_SHORT[c] for c in d.index])
    ax.set_xticks(range(d.shape[1]), [f"T{t}\n{names.get(t, '')}" for t in d.columns], fontsize=7)
    for i in range(d.shape[0]):
        for j in range(d.shape[1]):
            v = d.values[i, j] * 100
            if v >= 8:
                ax.text(j, i, f"{v:.0f}", ha="center", va="center", fontsize=7,
                        color="white" if v > 35 else INK)
    cb = fig.colorbar(im, ax=ax, fraction=0.02, pad=0.01)
    cb.set_label("% de párrafos del capítulo", color=INK_2)
    cb.outline.set_visible(False)
    ax.set_title("Temas por capítulo (TF-IDF + NMF, tema dominante por párrafo)")
    for s in ax.spines.values():
        s.set_visible(False)
    _finish(fig, ax, out)


def plot_semantic_embedding_map(emap: pd.DataFrame, method: str, out: Path) -> None:
    """Small multiples: each panel highlights one chapter over the others in grey
    (a scatter can only carry ~3 categorical hues safely)."""
    chapters = [c for c in CHAPTER_ORDER if c in set(emap.chapter)]
    fig, axes = plt.subplots(2, 3, figsize=(12, 7.2), sharex=True, sharey=True)
    for ax, ch in zip(axes.ravel(), chapters):
        other = emap[emap.chapter != ch]
        mine = emap[emap.chapter == ch]
        ax.scatter(other.x, other.y, s=9, color=DEEMPH, linewidths=0)
        ax.scatter(mine.x, mine.y, s=14, color=SERIES_1, edgecolors=SURFACE, linewidths=0.6)
        ax.set_title(f"{CHAPTER_SHORT[ch]} (n={len(mine)})", fontsize=10)
        ax.set_xticks([]); ax.set_yticks([])
        for s in ax.spines.values():
            s.set_color(GRID)
    for ax in axes.ravel()[len(chapters):]:
        ax.axis("off")
    fig.suptitle("Mapa semántico exploratorio de párrafos (UMAP 2D)", x=0.01, ha="left", fontweight="bold", fontsize=12)
    fig.tight_layout(rect=(0, 0.03, 1, 0.95))
    _finish(fig, None, out, f"Embeddings: {method}. La distancia 2D NO mide distancia semántica exacta.")


