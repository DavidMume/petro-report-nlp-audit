def plot_stylometry_pca(scores: pd.DataFrame, pca_var: pd.DataFrame, out: Path) -> None:
    chapters = [c for c in CHAPTER_ORDER if c in set(scores.chapter)]
    fig, axes = plt.subplots(2, 3, figsize=(11, 6.8), sharex=True, sharey=True)
    for ax, ch in zip(axes.ravel(), chapters):
        o, m = scores[scores.chapter != ch], scores[scores.chapter == ch]
        ax.scatter(o.pc1, o.pc2, s=16, color=DEEMPH, linewidths=0)
        ax.scatter(m.pc1, m.pc2, s=30, color=SERIES_1, edgecolors=SURFACE, linewidths=1.2)
        for _, r in m[m.flag_stylistic_outlier].iterrows():
            ax.annotate(f"{r.segment_id} (atípico)", (r.pc1, r.pc2), fontsize=7, color=INK, xytext=(4, 4), textcoords="offset points")
        ax.set_title(f"{CHAPTER_SHORT[ch]} (n={len(m)})", fontsize=10)
        ax.xaxis.grid(True); ax.yaxis.grid(True); ax.set_axisbelow(True)
    for ax in axes.ravel()[len(chapters):]:
        ax.axis("off")
    v = pca_var.explained_variance_ratio.values
    fig.supxlabel(f"PC1 ({v[0]*100:.0f}% var.)", fontsize=9, color=INK_2)
    fig.supylabel(f"PC2 ({v[1]*100:.0f}% var.)", fontsize=9, color=INK_2)
    fig.suptitle("Mapa estilométrico PCA de segmentos", x=0.01, ha="left", fontweight="bold", fontsize=12)
    fig.tight_layout(rect=(0.02, 0.04, 1, 0.95))
    _finish(fig, None, out, "Atípico = distancia de Mahalanobis > χ²(0,975). Diferencia estilística ≠ autoría ni uso de IA.")


