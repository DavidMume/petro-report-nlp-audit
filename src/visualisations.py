def plot_document_overview(paragraphs: pd.DataFrame, n_pages: int, out: Path) -> None:
    """Page-by-page structure map: each page coloured by chapter, bar height = words on page."""
    p = paragraphs[paragraphs.block_type != "heading"]
    words = p.groupby("page").n_words.sum().reindex(range(1, n_pages + 1), fill_value=0)
    chap = p.groupby("page").chapter.first().reindex(range(1, n_pages + 1)).ffill().bfill()
    fig, ax = plt.subplots(figsize=(11, 3.4))
    for i, ch in enumerate(CHAPTER_ORDER):
        idx = chap[chap == ch].index
        ax.bar(idx, words.loc[idx], width=0.86, color=CATEGORICAL[i], label=CHAPTER_SHORT[ch])
    ax.yaxis.grid(True)
    ax.set_axisbelow(True)
    ax.set_xlim(0.3, n_pages + 0.7)
    ax.set_xlabel("Página del PDF")
    ax.set_ylabel("Palabras analizadas")
    ax.set_title("Mapa estructural del documento: palabras por página y capítulo")
    ax.legend(ncol=6, loc="upper left", bbox_to_anchor=(0, 1.02), handlelength=1, columnspacing=1.2)
    ax.set_ylim(0, words.max() * 1.25)
    _finish(fig, ax, out, "Páginas sin barra: cubierta, portadillas o páginas solo con imagen (texto por OCR excluido del análisis).")


def plot_words_per_section(words_df: pd.DataFrame, out: Path, top_n: int = 30) -> None:
    d = words_df[~words_df.level2.str.startswith("Portadilla")].sort_values("words", ascending=False).head(top_n)
    fig, ax = plt.subplots(figsize=(9, 0.26 * len(d) + 1.2))
    _hbar(ax, [_short(f"{CHAPTER_SHORT.get(c, c).split()[0]} · {s}", 60) for c, s in zip(d.chapter, d.level2)],
          d.words.values)
    ax.set_title(f"Palabras por sección (top {top_n})")
    ax.set_xlabel("Palabras")
    _finish(fig, ax, out)


