"""Static, reproducible charts (matplotlib) written to outputs/charts/.

Every chart is regenerated by scripts/build_outputs.py from the tables in
outputs/tables/ and data/processed/ — nothing is drawn by hand. Each PNG has
a table twin (the CSV it was drawn from), which is the accessible view.

Design rules (see the project's dataviz notes): one axis per chart (no dual
axes); categorical hues assigned in a fixed order, never cycled, validated
for colour-vision deficiency; a single series uses one colour; magnitude uses
a single-hue ramp; polarity (verification outcomes) uses a blue↔red
diverging scale with a neutral grey midpoint; hairline solid grids; text in
ink colours, never in series colours; no pie charts.
"""

